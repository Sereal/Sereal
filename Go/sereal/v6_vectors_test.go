func mustHex(t testing.TB, s string) []byte {
	t.Helper()
	b, err := hex.DecodeString(s)
	if err != nil {
		t.Fatalf("bad hex %q: %v", s, err)
	}
	return b
}

// vecKey returns the checksum key used by the perl-generated sample packets
func vecKey(t testing.TB) *[16]byte {
	var k [16]byte
	copy(k[:], mustHex(t, vecKeyHex))
	return &k
}

// vecKey915Bytes returns the key of the Perl/Decoder/t/915 hand-built envelopes
func vecKey915Bytes() *[16]byte {
	var k [16]byte
	copy(k[:], vecKey915)
	return &k
}
